// Package common 提供客户端与服务端共享的无状态类型和协议工具。
//
// 本包只有类型、校验与编解码，不持有状态、不起 goroutine、不做 I/O。
// 两端对协议的理解必须完全一致，因此编码与解码共用同一套 Validate 规则。
//
// # 身份类型
//
// DeviceID 是 UUID 的规范文本形式（36 字符，带连字符）。它是设备的持久身份，
// 存在客户端身份文件里、作 devices 表主键，用 UUID 原本的样子最直接。
//
// 其余标识符是从 UUID 随机字节截取的定长小写十六进制串。截短各有理由——
// 有的要进固定宽度的二进制字段，有的只在一次会话内有效、短一点便于读日志：
//
//   - PeeringID（32 字符 / 16 字节） 一对设备的配对身份，是配置数据
//   - NetworkID（8 字符 / 4 字节）   虚拟网络身份
//   - SocketID（8 字符 / 4 字节）    一个 Worker 内的 UDP socket
//   - LinkToken（12 字符 / 6 字节）  一次链路尝试；6 字节是 GTUN 帧头的固定
//     字段宽度，这个长度由帧格式决定，不能改
//
// PeeringID 与 LinkToken 的区别是本设计的一个要点：PeeringID 是「这两台设备
// 配过对」，跨越任意多次建链，落库；LinkToken 是「这一次建链尝试」，随
// CONNECT 生成、随失败或拆链丢弃，不落库。数据面按 token 认帧，控制面按
// peering 认配置。
//
// # 三条不必存在的机制
//
// 以下三样东西刻意没有。写在这里是为了让后来者知道它们的缺席是设计结论，
// 不是遗漏——每一条都有替代方案，重新引入会连带引入它原本要解决的问题：
//
//   - 没有单调递增的「尝试编号」。LinkToken 已唯一标识一次尝试，编号的唯一
//     用途会是「拒绝编号低于水位的迟到消息」，而这套判定属于服务器推断隧道
//     状态的补偿机制，本设计不做这种推断（见 server 包的三条不变量）。
//   - 没有会话 ID 与请求关联 ID。会话身份就是连接本身：服务器按「当前连接
//     指针」判定消息归属，同一设备的重连靠顶替语义收敛。注册握手一条连接
//     只发生一次、TCP 有序，第一条确认即为本请求的答案，关联字段没有
//     可对应的并发场景。
//   - 没有配置代次（generation / revision）。前提是配置推送始终全量，
//     见 NetworkConfig 的不变量注释。
//   - 没有 ID 碰撞检测与重试。ID 由 UUID v4 生成，碰撞由数据库主键约束兜住
//     并报错，不做静默重试（见 randomHex）。
//
// # 校验的边界在哪
//
// Validate 只做「线上字节进入内存」这一层的结构校验：长度、字符集、字段间的
// 交叉约束、地址是否可用。它不做业务判断——链路该不该建、对端在不在线，
// 都是 server 包的事。解码允许未知字段（向前兼容），不允许畸形结构。
